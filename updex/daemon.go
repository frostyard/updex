const (
	daemonUnitName = "updex-update"

	// daemonMarker is the comment written as the first line of the unit files
	// that `updex daemon enable` writes to /etc/systemd/system. It is the
	// ownership signal: `updex daemon disable` removes only a unit file that
	// carries it (or matches the legacy text, see daemon_legacy.go).
	daemonMarker = "Generated by updex daemon enable; updex daemon disable removes this file."

	// maxUnitRead bounds how much of a unit file updex reads to classify it
	// or to find its schedule. updex units are about 1 KiB.
	maxUnitRead = 16 << 10
)

// Where the daemon's unit files in use come from, reported as
// DaemonStatusResult.Source.
const (
	// DaemonSourcePackaged means the OS package ships the units in
	// /usr/lib/systemd/system.
	DaemonSourcePackaged = "packaged"
	// DaemonSourceEtc means the units are in /etc/systemd/system, where they
	// override any packaged units.
	DaemonSourceEtc = "etc"
)

// DaemonUnits returns the configuration of the automatic update timer and
// service. It is the single source of the unit text: `updex daemon enable`
// writes it to /etc/systemd/system (with an ownership marker) when no package
// ships the units, and the release build writes it to the files that the
// frostyard-updex package installs under /usr/lib/systemd/system
// (`updex units`, scripts/units.sh), so the two cannot drift. A contract test
// compares them. Every call returns new values that the caller may change.
//
// The service is a sandboxed oneshot that runs
// `/usr/bin/updex features update --no-refresh`: it downloads, verifies and
// links, and never refreshes, so a new revision takes effect at the next boot
// (ADR-0016). It waits for the network and skips a run on battery. The timer
// fires every 6 hours with up to an hour of random delay and catches up a
// missed run.
func DaemonUnits() (*systemd.TimerConfig, *systemd.ServiceConfig) {
	timer := &systemd.TimerConfig{
		Name:           daemonUnitName,
		Description:    "Automatic sysext updates",
		OnCalendar:     "*-*-* 00/6:00:00",
		Persistent:     true,
		RandomDelaySec: 3600,
	}
	service := &systemd.ServiceConfig{
		Name:        daemonUnitName,
		Description: "Automatic sysext update service",
		Wants:       []string{"network-online.target"},
		After:       []string{"network-online.target"},
		// A host without a battery counts as on AC power, so it always runs.
		Conditions: []string{"ConditionACPower=true"},
		ExecStart:  "/usr/bin/updex features update --no-refresh",
		Type:       "oneshot",
		// A backstop for a stuck run: systemd stops the service after 2
		// hours, which releases /run/updex/lock. The per-request timeouts
		// and ADR-0008's bounded retries normally end a run long before.
		TimeoutStartSec: "2h",
		// Sandbox the root oneshot: read-only /usr and /etc, no new
		// privileges, and restricted syscalls/address families.
		Sandbox: true,
	}
	return timer, service
}

// daemonUnitPaths returns the absolute paths of the daemon's timer and
// service unit files in the client's systemd manager unit directory
// (/etc/systemd/system in production), in that order.
func (c *Client) daemonUnitPaths() []string {
	return []string{
		filepath.Join(c.systemd.UnitPath, daemonUnitName+".timer"),
		filepath.Join(c.systemd.UnitPath, daemonUnitName+".service"),
	}
}

// EnableDaemon enables and starts the automatic update timer.
//
// When the OS package ships the timer (the manager's packaged unit
// directory, /usr/lib/systemd/system in production), it only enables and
// starts it and writes no file. Otherwise, for an updex binary installed
// without the package, it writes the units to the unit directory
// (/etc/systemd/system) with an ownership marker, reloads systemd, then
// enables and starts the timer, and refuses when unit files already occupy
// those paths. "Enable and start" is `systemctl enable` then `systemctl
// start`, the same as `enable --now`.
//
// With opts.DryRun it reports the unit files and actions without writing any
// file or calling systemctl; the already-installed precondition still applies.
// Except in a dry run it holds the operation lock; when another updex
// operation holds it, EnableDaemon changes nothing and returns an error that
// wraps ErrBusy.
func (c *Client) EnableDaemon(ctx context.Context, opts EnableDaemonOptions) (*DaemonActionResult, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("enable daemon: %w", err)
	}
	release, err := c.lockMutation(opts.DryRun)
	if err != nil {
		return nil, err
	}
	defer release()

	timerUnit := daemonUnitName + ".timer"

	if c.systemd.PackagedExists(daemonUnitName) {
		return c.enablePackagedDaemon(ctx, opts, timerUnit)
	}

	if c.systemd.Exists(daemonUnitName) {
		return nil, fmt.Errorf("timer already installed; run 'updex daemon disable' first to reinstall")
	}

	unitFiles := c.daemonUnitPaths()
	if opts.DryRun {
		return &DaemonActionResult{
			Success:   true,
			DryRun:    true,
			UnitFiles: unitFiles,
			Message: fmt.Sprintf("Would install %s and %s, then enable and start %s",
				unitFiles[0], unitFiles[1], timerUnit),
		}, nil
	}

	timer, service := DaemonUnits()
	timer.Comment = daemonMarker
	service.Comment = daemonMarker

	if err := c.systemd.Install(ctx, timer, service); err != nil {
		return nil, fmt.Errorf("failed to install timer: %w", err)
	}
	if err := c.systemd.Enable(ctx, timerUnit); err != nil {
		return nil, fmt.Errorf("failed to enable timer: %w", err)
	}
	if err := c.systemd.Start(ctx, timerUnit); err != nil {
		return nil, fmt.Errorf("failed to start timer: %w", err)
	}

	return &DaemonActionResult{
		Success:   true,
		UnitFiles: unitFiles,
		Message:   "Auto-update daemon enabled",
	}, nil
}

// enablePackagedDaemon enables and starts the packaged timer. It writes
// nothing. Unit files in the /etc unit directory override the packaged ones,
// so their presence is reported in the message.
func (c *Client) enablePackagedDaemon(ctx context.Context, opts EnableDaemonOptions, timerUnit string) (*DaemonActionResult, error) {
	unitFiles := c.systemd.PackagedUnitPaths(daemonUnitName)
	override := ""
	if c.systemd.Exists(daemonUnitName) {
		override = fmt.Sprintf("; note: unit files in %s override the packaged units (run 'updex daemon disable' to remove the ones updex wrote)", c.systemd.UnitPath)
	}

	if opts.DryRun {
		return &DaemonActionResult{
			Success:   true,
			DryRun:    true,
			Packaged:  true,
			UnitFiles: unitFiles,
			Message: fmt.Sprintf("Would enable and start %s (units shipped by the package: %s); nothing is written%s",
				timerUnit, c.systemd.PackagedUnitPath, override),
		}, nil
	}

	if err := c.systemd.Enable(ctx, timerUnit); err != nil {
		return nil, fmt.Errorf("failed to enable timer: %w", err)
	}
	if err := c.systemd.Start(ctx, timerUnit); err != nil {
		return nil, fmt.Errorf("failed to start timer: %w", err)
	}
	return &DaemonActionResult{
		Success:   true,
		Packaged:  true,
		UnitFiles: unitFiles,
		Message:   "Auto-update daemon enabled" + override,
	}, nil
}

// unitOwnership is the result of classifying a unit file in the /etc unit
// directory.
type unitOwnership int

const (
	unitAbsent  unitOwnership = iota // no file at the path
	unitOurs                         // carries the updex marker or matches the legacy text
	unitForeign                      // a regular file that updex cannot prove it wrote
)

// classifyUnitFile decides whether the file at path is one that updex wrote.
// It uses os.Lstat and refuses anything that is not a regular file
// (ADR-0005), so it never reads through, or later deletes, a symlink or a
// directory. A file is updex's when its first line is the marker comment, or
// when its whole content equals one of the legacy texts (the ADR-0007 units
// that older releases wrote before the marker existed). Exact content match
// is deliberately strict: a unit that an administrator edited, or that an
// older release wrote in another shape, is foreign and stays.
func classifyUnitFile(path string, legacy []string) (unitOwnership, error) {
	info, err := os.Lstat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return unitAbsent, nil
		}
		return unitForeign, fmt.Errorf("inspect unit path %s: %w", path, err)
	}
	if !info.Mode().IsRegular() {
		return unitForeign, fmt.Errorf("unit path %s exists and is not a regular file; refusing to remove it", path)
	}
	content, err := readUnitFile(path)
	if err != nil {
		return unitForeign, err
	}
	first, _, _ := strings.Cut(content, "\n")
	if first == "# "+daemonMarker || slices.Contains(legacy, content) {
		return unitOurs, nil
	}
	return unitForeign, nil
}

// readUnitFile reads at most maxUnitRead bytes of a unit file.
func readUnitFile(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", fmt.Errorf("read unit file %s: %w", path, err)
	}
	defer func() { _ = f.Close() }()
	data, err := io.ReadAll(io.LimitReader(f, maxUnitRead))
	if err != nil {
		return "", fmt.Errorf("read unit file %s: %w", path, err)
	}
	return string(data), nil
}

// daemonRemovalPlan lists what DisableDaemon does with the /etc unit files.
type daemonRemovalPlan struct {
	remove []string // files updex wrote: removed
	keep   []string // files updex cannot prove it wrote: kept
	errs   []error  // files that cannot be classified or are not regular files
}

// planDaemonRemoval classifies the timer and service files in the /etc unit
// directory.
func (c *Client) planDaemonRemoval() daemonRemovalPlan {
	var plan daemonRemovalPlan
	paths := c.daemonUnitPaths()
	for i, legacy := range [][]string{legacyTimerUnits, legacyServiceUnits} {
		state, err := classifyUnitFile(paths[i], legacy)
		switch {
		case err != nil:
			plan.errs = append(plan.errs, err)
		case state == unitOurs:
			plan.remove = append(plan.remove, paths[i])
		case state == unitForeign:
			plan.keep = append(plan.keep, paths[i])
		}
	}
	return plan
}

// DisableDaemon stops and disables the automatic update timer, then removes
// the unit files that updex wrote to /etc/systemd/system and reloads systemd.
//
// It removes only a file that carries the updex marker or equals the unit
// text that an older updex wrote before the marker existed. It never deletes
// any other file: the OS image can ship a unit of that name in /etc, and an
// administrator can edit one. Those files are kept and reported in the
// result's KeptFiles and Message. Units that the OS package ships in
// /usr/lib/systemd/system stay; disabling stops the timer from running.
// Every step is attempted, and all failures are returned together.
//
// With opts.DryRun it reports the unit files and actions without stopping,
// disabling, or removing anything; the not-installed precondition still
// applies. Except in a dry run it holds the operation lock; when another
// updex operation holds it, DisableDaemon changes nothing and returns an error
// that wraps ErrBusy.
func (c *Client) DisableDaemon(ctx context.Context, opts DisableDaemonOptions) (*DaemonActionResult, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("disable daemon: %w", err)
	}
	release, err := c.lockMutation(opts.DryRun)
	if err != nil {
		return nil, err
	}
	defer release()
	packaged := c.systemd.PackagedExists(daemonUnitName)
	if !packaged && !c.systemd.Exists(daemonUnitName) {
		return nil, fmt.Errorf("timer not installed; nothing to disable")
	}

	timerUnit := daemonUnitName + ".timer"
	plan := c.planDaemonRemoval()
	kept := keptNote(plan.keep)

	if opts.DryRun {
		if err := errors.Join(plan.errs...); err != nil {
			return nil, fmt.Errorf("failed to remove timer: %w", err)
		}
		message := fmt.Sprintf("Would stop and disable %s and reload systemd", timerUnit)
		if len(plan.remove) > 0 {
			message = fmt.Sprintf("Would stop and disable %s, remove %s, and reload systemd",
				timerUnit, strings.Join(plan.remove, " and "))
		}
		return &DaemonActionResult{
			Success:   true,
			DryRun:    true,
			Packaged:  packaged,
			UnitFiles: plan.remove,
			KeptFiles: plan.keep,
			Message:   message + kept,
		}, nil
	}

	errs := slices.Clone(plan.errs)
	for i, err := range errs {
		errs[i] = fmt.Errorf("remove unit: %w", err)
	}
	if err := c.systemd.Stop(ctx, timerUnit); err != nil {
		errs = append(errs, fmt.Errorf("stop timer: %w", err))
	}
	if err := c.systemd.Disable(ctx, timerUnit); err != nil {
		errs = append(errs, fmt.Errorf("disable timer: %w", err))
	}
	var removed []string
	for _, path := range plan.remove {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			errs = append(errs, fmt.Errorf("remove %s: %w", filepath.Base(path), err))
			continue
		}
		removed = append(removed, path)
	}
	if err := c.systemd.DaemonReload(ctx); err != nil {
		errs = append(errs, fmt.Errorf("daemon-reload: %w", err))
	}
	if err := errors.Join(errs...); err != nil {
		return nil, fmt.Errorf("failed to remove timer: %w", err)
	}

	return &DaemonActionResult{
		Success:   true,
		Packaged:  packaged,
		UnitFiles: removed,
		KeptFiles: plan.keep,
		Message:   "Auto-update daemon disabled" + kept,
	}, nil
}

// keptNote returns the message suffix that names the unit files that
// DisableDaemon kept, or "" when it kept none.
func keptNote(kept []string) string {
	if len(kept) == 0 {
		return ""
	}
	return fmt.Sprintf("; kept %s (not written by updex; remove by hand if unwanted)", strings.Join(kept, " and "))
}

// daemonUnitFileInUse returns the path of the unit file that systemd uses
// for the unit named daemonUnitName+suffix: the file in the /etc unit
// directory when one exists (it overrides), else the packaged file when one
// exists. ok is false when neither exists.
func (c *Client) daemonUnitFileInUse(suffix string) (path, source string, ok bool) {
	candidates := []struct{ dir, source string }{
		{c.systemd.UnitPath, DaemonSourceEtc},
		{c.systemd.PackagedUnitPath, DaemonSourcePackaged},
	}
	for _, candidate := range candidates {
		if candidate.dir == "" {
			continue
		}
		p := filepath.Join(candidate.dir, daemonUnitName+suffix)
		if _, err := os.Lstat(p); err == nil || !os.IsNotExist(err) {
			return p, candidate.source, true
		}
	}
	return "", "", false
}

// DaemonStatus reports whether the automatic update timer is installed,
// enabled, and active, which unit files are in use, its schedule, the next
// run, and the time and result of the last run.
//
// Installed means a timer unit file exists in /etc/systemd/system or in the
// packaged directory. Source is "etc" when the timer file in use is in
// /etc/systemd/system (it overrides the packaged one), else "packaged". The
// next run and the last run come from systemd (`systemctl show`): the
// timer's NextElapseUSecRealtime, and the service's ExecMainExitTimestamp and
// Result. They are returned as systemd prints them. NextRun is empty when no
// run is scheduled (the timer is not active). LastRun and LastResult are empty
// when the service never ran since boot. A runner that cannot read properties
// leaves all three empty.
func (c *Client) DaemonStatus(ctx context.Context, _ DaemonStatusOptions) (*DaemonStatusResult, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("get daemon status: %w", err)
	}

	status := &DaemonStatusResult{}
	timerPath, source, timerFound := c.daemonUnitFileInUse(".timer")
	if !timerFound {
		return status, nil
	}
	status.Installed = true
	status.Source = source
	for _, suffix := range []string{".timer", ".service"} {
		if path, _, ok := c.daemonUnitFileInUse(suffix); ok {
			status.UnitFiles = append(status.UnitFiles, path)
		}
	}
	status.Schedule = readOnCalendar(timerPath)

	timerUnit := daemonUnitName + ".timer"
	enabled, err := c.systemd.IsEnabled(ctx, timerUnit)
	if err != nil {
		return nil, fmt.Errorf("get daemon status: query enabled state: %w", err)
	}
	active, err := c.systemd.IsActive(ctx, timerUnit)
	if err != nil {
		return nil, fmt.Errorf("get daemon status: query active state: %w", err)
	}
	status.Enabled = enabled
	status.Active = active

	next, err := c.showDaemonProperty(ctx, timerUnit, "NextElapseUSecRealtime")
	if err != nil {
		return nil, fmt.Errorf("get daemon status: query next run: %w", err)
	}
	status.NextRun = next
	serviceUnit := daemonUnitName + ".service"
	last, err := c.showDaemonProperty(ctx, serviceUnit, "ExecMainExitTimestamp")
	if err != nil {
		return nil, fmt.Errorf("get daemon status: query last run: %w", err)
	}
	if last != "" {
		result, err := c.showDaemonProperty(ctx, serviceUnit, "Result")
		if err != nil {
			return nil, fmt.Errorf("get daemon status: query last result: %w", err)
		}
		status.LastRun = last
		status.LastResult = result
	}
	return status, nil
}

// showDaemonProperty reads one systemd property and maps "no value" (an empty
// string, "n/a", or "0") to "". A runner without ShowRunner support yields
// "" and no error, because the state is unknown rather than failed.
func (c *Client) showDaemonProperty(ctx context.Context, unit, property string) (string, error) {
	value, err := c.systemd.Show(ctx, unit, property)
	if err != nil {
		if errors.Is(err, systemd.ErrShowUnsupported) {
			return "", nil
		}
		return "", err
	}
	switch value {
	case "n/a", "0":
		return "", nil
	}
	return value, nil
}

// readOnCalendar returns the OnCalendar= values of the timer file at path,
// joined with ", ", or "" when the file cannot be read or has none. It reports
// the schedule of the file in use, whoever wrote it.
func readOnCalendar(path string) string {
	f, err := os.Open(path)
	if err != nil {
		return ""
	}
	defer func() { _ = f.Close() }()
	var values []string
	scanner := bufio.NewScanner(io.LimitReader(f, maxUnitRead))
	for scanner.Scan() {
		if value, ok := strings.CutPrefix(strings.TrimSpace(scanner.Text()), "OnCalendar="); ok && value != "" {
			values = append(values, value)
		}
	}
	return strings.Join(values, ", ")
}
