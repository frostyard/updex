const (
	daemonUnitName = "updex-update"

	// suiteSwitchUnitName is the boot-time service that links and merges the
	// running suite's images after a suite switch (ADR-0021).
	suiteSwitchUnitName = "updex-suite-switch"

	// daemonMarker is the comment written as the first line of the unit files
	// that `updex daemon enable` writes to /etc/systemd/system. It is the
	// ownership signal: `updex daemon disable` removes only a unit file that
	// carries it (or matches the legacy text, see daemon_legacy.go).
	daemonMarker = "Generated by updex daemon enable; updex daemon disable removes this file."

	// maxUnitRead bounds how much of a unit file updex reads to classify it
	// or to find its schedule. updex units are about 1 KiB.
	maxUnitRead = 16 << 10
)

// Where the daemon's unit files in use come from, reported as
// DaemonStatusResult.Source.
const (
	// DaemonSourcePackaged means the OS package ships the units in
	// /usr/lib/systemd/system.
	DaemonSourcePackaged = "packaged"
	// DaemonSourceEtc means the units are in /etc/systemd/system, where they
	// override any packaged units.
	DaemonSourceEtc = "etc"
)

// DaemonUnits returns the configuration of the automatic update timer and
// service. It is the single source of the unit text: `updex daemon enable`
// writes it to /etc/systemd/system (with an ownership marker) when no package
// ships the units, and the release build writes it to the files that the
// frostyard-updex package installs under /usr/lib/systemd/system
// (`updex units`, scripts/units.sh), so the two cannot drift. A contract test
// compares them. Every call returns new values that the caller may change.
//
// The service is a sandboxed oneshot that runs
// `/usr/bin/updex features update --no-refresh`: it downloads, verifies and
// links, and never refreshes, so a new revision takes effect at the next boot
// (ADR-0016). It waits for the network and skips a run on battery. The timer
// fires every 6 hours with up to an hour of random delay and catches up a
// missed run.
func DaemonUnits() (*systemd.TimerConfig, *systemd.ServiceConfig) {
	timer := &systemd.TimerConfig{
		Name:           daemonUnitName,
		Description:    "Automatic sysext updates",
		OnCalendar:     "*-*-* 00/6:00:00",
		Persistent:     true,
		RandomDelaySec: 3600,
	}
	service := &systemd.ServiceConfig{
		Name:        daemonUnitName,
		Description: "Automatic sysext update service",
		Wants:       []string{"network-online.target"},
		After:       []string{"network-online.target"},
		// A host without a battery counts as on AC power, so it always runs.
		Conditions: []string{"ConditionACPower=true"},
		ExecStart:  "/usr/bin/updex features update --no-refresh",
		Type:       "oneshot",
		// A backstop for a stuck run: systemd stops the service after 2
		// hours, which releases /run/updex/lock. The per-request timeouts
		// and ADR-0008's bounded retries normally end a run long before.
		TimeoutStartSec: "2h",
		// Sandbox the root oneshot: read-only /usr and /etc, no new
		// privileges, and restricted syscalls/address families.
		Sandbox: true,
	}
	return timer, service
}

// SuiteSwitchUnit returns the configuration of updex-suite-switch.service
// (ADR-0021), the sibling of DaemonUnits: `updex daemon enable` writes and
// enables it beside the timer when no package ships the units, and the
// release build writes it to the file that the frostyard-updex package
// installs under /usr/lib/systemd/system. Every call returns a new value.
//
// It is a oneshot that runs `/usr/bin/updex features update --suite-switch`
// once per boot, after the network is online and before
// updex-update.service: on the first boot after a suite switch it links the
// running suite's image of every feature whose link still names the other
// suite's image, and refreshes, so the feature is merged on that boot; on
// every other boot it reads the links and does nothing. WantedBy=
// multi-user.target enables it. DefaultDependencies=no keeps
// multi-user.target from waiting for it (and so for network-online.target);
// the unit names the usual basic dependencies itself. It refreshes, so it
// takes only the RefreshSandboxDirectives, not the timer service's sandbox,
// whose private mount namespace would hide the merged images from the host.
// It has no ConditionACPower=: a feature that is missing matters on battery
// too.
//
// A failed run (no image of the new suite yet, no network, a busy lock)
// restarts after RestartSec= (Restart=on-failure, ADR-0022). The start limit
// (StartLimitIntervalSec=, StartLimitBurst=: 1 start and at most 3 retries
// in the window) bounds the retries; after that the unit stays failed until
// the next boot or `systemctl reset-failed`. A retry waits in the unit's own
// auto-restart state with no job queued, so no other unit waits for it.
func SuiteSwitchUnit() *systemd.ServiceConfig {
	return &systemd.ServiceConfig{
		Name:        suiteSwitchUnitName,
		Description: "Link the running suite's sysext images after a suite switch",
		Wants:       []string{"network-online.target"},
		After:       []string{"sysinit.target", "basic.target", "network-online.target"},
		Before:      []string{daemonUnitName + ".service", "shutdown.target"},
		UnitDirectives: []string{
			"DefaultDependencies=no",
			"Conflicts=shutdown.target",
			"StartLimitIntervalSec=6h",
			"StartLimitBurst=4",
		},
		ExecStart:       "/usr/bin/updex features update --suite-switch",
		Type:            "oneshot",
		TimeoutStartSec: "2h",
		Directives: append([]string{
			"Restart=on-failure",
			"RestartSec=5min",
		}, systemd.RefreshSandboxDirectives...),
		WantedBy: []string{"multi-user.target"},
	}
}

// suiteSwitchUnitPath returns the path of updex-suite-switch.service in the
// client's systemd manager unit directory (/etc/systemd/system in
// production).
func (c *Client) suiteSwitchUnitPath() string {
	return filepath.Join(c.systemd.UnitPath, suiteSwitchUnitName+".service")
}

// daemonUnitPaths returns the absolute paths of the daemon's timer and
// service unit files in the client's systemd manager unit directory
// (/etc/systemd/system in production), in that order.
func (c *Client) daemonUnitPaths() []string {
	return []string{
		filepath.Join(c.systemd.UnitPath, daemonUnitName+".timer"),
		filepath.Join(c.systemd.UnitPath, daemonUnitName+".service"),
	}
}

// EnableDaemon enables and starts the automatic update timer.
//
// When the OS package ships the timer (the manager's packaged unit
// directory, /usr/lib/systemd/system in production), it only enables and
// starts it and writes no file. Otherwise, for an updex binary installed
// without the package, it writes the units to the unit directory
// (/etc/systemd/system) with an ownership marker, reloads systemd, then
// enables and starts the timer, and refuses when unit files already occupy
// those paths. "Enable and start" is `systemctl enable` then `systemctl
// start`, the same as `enable --now`.
//
// With opts.DryRun it reports the unit files and actions without writing any
// file or calling systemctl; the already-installed precondition still applies.
// Except in a dry run it holds the operation lock; when another updex
// operation holds it, EnableDaemon changes nothing and returns an error that
// wraps ErrBusy.
func (c *Client) EnableDaemon(ctx context.Context, opts EnableDaemonOptions) (*DaemonActionResult, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("enable daemon: %w", err)
	}
	release, err := c.lockMutation(opts.DryRun)
	if err != nil {
		return nil, err
	}
	defer release()

	timerUnit := daemonUnitName + ".timer"

	if c.systemd.PackagedExists(daemonUnitName) {
		return c.enablePackagedDaemon(ctx, opts, timerUnit)
	}

	if c.systemd.Exists(daemonUnitName) {
		return nil, fmt.Errorf("timer already installed; run 'updex daemon disable' first to reinstall")
	}
	suitePath := c.suiteSwitchUnitPath()
	if _, err := os.Lstat(suitePath); err == nil || !os.IsNotExist(err) {
		return nil, fmt.Errorf("unit file %s already exists; run 'updex daemon disable' first to reinstall", suitePath)
	}

	suiteUnit := suiteSwitchUnitName + ".service"
	unitFiles := append(c.daemonUnitPaths(), suitePath)
	if opts.DryRun {
		return &DaemonActionResult{
			Success:   true,
			DryRun:    true,
			UnitFiles: unitFiles,
			Message: fmt.Sprintf("Would install %s, %s and %s, then enable and start %s and enable %s",
				unitFiles[0], unitFiles[1], unitFiles[2], timerUnit, suiteUnit),
		}, nil
	}

	timer, service := DaemonUnits()
	timer.Comment = daemonMarker
	service.Comment = daemonMarker
	suite := SuiteSwitchUnit()
	suite.Comment = daemonMarker

	if err := c.systemd.Install(ctx, timer, service); err != nil {
		return nil, fmt.Errorf("failed to install timer: %w", err)
	}
	if err := c.systemd.InstallService(ctx, suite); err != nil {
		return nil, fmt.Errorf("failed to install %s: %w", suiteUnit, err)
	}
	if err := c.systemd.Enable(ctx, timerUnit); err != nil {
		return nil, fmt.Errorf("failed to enable timer: %w", err)
	}
	if err := c.systemd.Start(ctx, timerUnit); err != nil {
		return nil, fmt.Errorf("failed to start timer: %w", err)
	}
	// The boot-time unit is enabled, not started: it acts at the next boot.
	if err := c.systemd.Enable(ctx, suiteUnit); err != nil {
		return nil, fmt.Errorf("failed to enable %s: %w", suiteUnit, err)
	}

	return &DaemonActionResult{
		Success:   true,
		UnitFiles: unitFiles,
		Message:   "Auto-update daemon enabled",
	}, nil
}

// enablePackagedDaemon enables and starts the packaged timer. It writes
// nothing. Unit files in the /etc unit directory override the packaged ones,
// so their presence is reported in the message.
func (c *Client) enablePackagedDaemon(ctx context.Context, opts EnableDaemonOptions, timerUnit string) (*DaemonActionResult, error) {
	unitFiles := c.systemd.PackagedUnitPaths(daemonUnitName)
	override := ""
	if c.systemd.Exists(daemonUnitName) {
		override = fmt.Sprintf("; note: unit files in %s override the packaged units (run 'updex daemon disable' to remove the ones updex wrote)", c.systemd.UnitPath)
	}
	suiteUnit := suiteSwitchUnitName + ".service"
	suitePath, _, suiteFound := c.unitFileInUse(suiteUnit)
	enableSuite := suiteFound && !isMaskLink(suitePath)
	suiteNote := ""
	switch {
	case enableSuite:
		if packaged := filepath.Join(c.systemd.PackagedUnitPath, suiteUnit); suitePath == packaged {
			unitFiles = append(unitFiles, packaged)
		}
	case suiteFound:
		suiteNote = fmt.Sprintf("; %s is masked and stays disabled", suiteUnit)
	}
	// An older package ships only the timer and the service: then there is
	// nothing to enable and nothing to say.

	if opts.DryRun {
		action := fmt.Sprintf("Would enable and start %s", timerUnit)
		if enableSuite {
			action = fmt.Sprintf("Would enable and start %s and enable %s", timerUnit, suiteUnit)
		}
		return &DaemonActionResult{
			Success:   true,
			DryRun:    true,
			Packaged:  true,
			UnitFiles: unitFiles,
			Message: fmt.Sprintf("%s (units shipped by the package: %s); nothing is written%s%s",
				action, c.systemd.PackagedUnitPath, suiteNote, override),
		}, nil
	}

	if err := c.systemd.Enable(ctx, timerUnit); err != nil {
		return nil, fmt.Errorf("failed to enable timer: %w", err)
	}
	if err := c.systemd.Start(ctx, timerUnit); err != nil {
		return nil, fmt.Errorf("failed to start timer: %w", err)
	}
	if enableSuite {
		if err := c.systemd.Enable(ctx, suiteUnit); err != nil {
			return nil, fmt.Errorf("failed to enable %s: %w", suiteUnit, err)
		}
	}
	return &DaemonActionResult{
		Success:   true,
		Packaged:  true,
		UnitFiles: unitFiles,
		Message:   "Auto-update daemon enabled" + suiteNote + override,
	}, nil
}

// unitOwnership is the result of classifying a unit file in the /etc unit
// directory.
type unitOwnership int

const (
	unitAbsent  unitOwnership = iota // no file at the path
	unitOurs                         // carries the updex marker or matches the legacy text
	unitForeign                      // a regular file that updex cannot prove it wrote
	unitMasked                       // a symlink to /dev/null: `systemctl mask`
)

// classifyUnitFile decides whether the file at path is one that updex wrote.
// It uses os.Lstat and refuses anything that is not a regular file
// (ADR-0005), so it never reads through, or later deletes, a symlink or a
// directory. A symlink to /dev/null is the one exception: it is a systemd
// mask, which updex never removes (DisableDaemon reports it instead), so it is
// classified as unitMasked rather than refused. A file is updex's when its
// first line is the marker comment, or when its whole content equals one of
// the legacy texts (the ADR-0007 units that older releases wrote before the
// marker existed). Exact content match is deliberately strict: a unit that an
// administrator edited, or that an older release wrote in another shape, is
// foreign and stays.
func classifyUnitFile(path string, legacy []string) (unitOwnership, error) {
	info, err := os.Lstat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return unitAbsent, nil
		}
		return unitForeign, fmt.Errorf("inspect unit path %s: %w", path, err)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		if isMaskLink(path) {
			return unitMasked, nil
		}
		return unitForeign, fmt.Errorf("unit path %s exists and is not a regular file; refusing to remove it", path)
	}
	if !info.Mode().IsRegular() {
		return unitForeign, fmt.Errorf("unit path %s exists and is not a regular file; refusing to remove it", path)
	}
	content, err := readUnitFile(path)
	if err != nil {
		return unitForeign, err
	}
	first, _, _ := strings.Cut(content, "\n")
	if first == "# "+daemonMarker || slices.Contains(legacy, content) {
		return unitOurs, nil
	}
	return unitForeign, nil
}

// isMaskLink reports whether path is a symlink to /dev/null, the shape that
// `systemctl mask` writes. It reads the link target only; it never follows it.
func isMaskLink(path string) bool {
	info, err := os.Lstat(path)
	if err != nil || info.Mode()&os.ModeSymlink == 0 {
		return false
	}
	target, err := os.Readlink(path)
	return err == nil && target == os.DevNull
}

// readUnitFile reads at most maxUnitRead bytes of a unit file.
func readUnitFile(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", fmt.Errorf("read unit file %s: %w", path, err)
	}
	defer func() { _ = f.Close() }()
	data, err := io.ReadAll(io.LimitReader(f, maxUnitRead))
	if err != nil {
		return "", fmt.Errorf("read unit file %s: %w", path, err)
	}
	return string(data), nil
}

// daemonRemovalPlan lists what DisableDaemon does with the /etc unit files.
type daemonRemovalPlan struct {
	remove []string // files updex wrote: removed
	keep   []string // files updex cannot prove it wrote: kept
	masked []string // symlinks to /dev/null (systemd masks): kept, never removed
	errs   []error  // files that cannot be classified or are not regular files
}

// planDaemonRemoval classifies the timer and service files in the /etc unit
// directory.
func (c *Client) planDaemonRemoval() daemonRemovalPlan {
	var plan daemonRemovalPlan
	// updex-suite-switch.service has no legacy text: every updex that writes
	// it writes the marker.
	paths := append(c.daemonUnitPaths(), c.suiteSwitchUnitPath())
	for i, legacy := range [][]string{legacyTimerUnits, legacyServiceUnits, nil} {
		state, err := classifyUnitFile(paths[i], legacy)
		switch {
		case err != nil:
			plan.errs = append(plan.errs, err)
		case state == unitOurs:
			plan.remove = append(plan.remove, paths[i])
		case state == unitMasked:
			plan.masked = append(plan.masked, paths[i])
		case state == unitForeign:
			plan.keep = append(plan.keep, paths[i])
		}
	}
	return plan
}

// DisableDaemon stops and disables the automatic update timer, then removes
// the unit files that updex wrote to /etc/systemd/system and reloads systemd.
//
// It removes only a file that carries the updex marker or equals the unit
// text that an older updex wrote before the marker existed. It never deletes
// any other file: the OS image can ship a unit of that name in /etc, and an
// administrator can edit one. Those files are kept and reported in the
// result's KeptFiles and Message. A unit that is masked (a symlink to
// /dev/null, the shape `systemctl mask` writes) is kept too and reported in
// MaskedFiles: disable stops and disables the timer, but only
// `systemctl unmask` removes a mask. Units that the OS package ships in
// /usr/lib/systemd/system stay; disabling stops the timer from running.
// Every step is attempted, and all failures are returned together.
//
// With opts.DryRun it reports the unit files and actions without stopping,
// disabling, or removing anything; the not-installed precondition still
// applies. Except in a dry run it holds the operation lock; when another
// updex operation holds it, DisableDaemon changes nothing and returns an error
// that wraps ErrBusy.
func (c *Client) DisableDaemon(ctx context.Context, opts DisableDaemonOptions) (*DaemonActionResult, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("disable daemon: %w", err)
	}
	release, err := c.lockMutation(opts.DryRun)
	if err != nil {
		return nil, err
	}
	defer release()
	packaged := c.systemd.PackagedExists(daemonUnitName)
	if !packaged && !c.systemd.Exists(daemonUnitName) {
		return nil, fmt.Errorf("timer not installed; nothing to disable")
	}

	timerUnit := daemonUnitName + ".timer"
	plan := c.planDaemonRemoval()
	notes := keptNote(plan.keep) + maskedNote(plan.masked)
	// The boot-time unit is disabled with the timer when a file of it exists
	// and is not a mask (ADR-0021).
	suiteUnit := suiteSwitchUnitName + ".service"
	suitePath, _, suiteFound := c.unitFileInUse(suiteUnit)
	disableSuite := suiteFound && !isMaskLink(suitePath)

	if opts.DryRun {
		if err := errors.Join(plan.errs...); err != nil {
			return nil, fmt.Errorf("failed to remove timer: %w", err)
		}
		disabled := timerUnit
		if disableSuite {
			disabled = timerUnit + " (and disable " + suiteUnit + ")"
		}
		message := fmt.Sprintf("Would stop and disable %s and reload systemd", disabled)
		if len(plan.remove) > 0 {
			message = fmt.Sprintf("Would stop and disable %s, remove %s, and reload systemd",
				disabled, strings.Join(plan.remove, " and "))
		}
		return &DaemonActionResult{
			Success:     true,
			DryRun:      true,
			Packaged:    packaged,
			UnitFiles:   plan.remove,
			KeptFiles:   plan.keep,
			MaskedFiles: plan.masked,
			Message:     message + notes,
		}, nil
	}

	errs := slices.Clone(plan.errs)
	for i, err := range errs {
		errs[i] = fmt.Errorf("remove unit: %w", err)
	}
	if err := c.systemd.Stop(ctx, timerUnit); err != nil {
		errs = append(errs, fmt.Errorf("stop timer: %w", err))
	}
	if err := c.systemd.Disable(ctx, timerUnit); err != nil {
		errs = append(errs, fmt.Errorf("disable timer: %w", err))
	}
	if disableSuite {
		if err := c.systemd.Disable(ctx, suiteUnit); err != nil {
			errs = append(errs, fmt.Errorf("disable %s: %w", suiteUnit, err))
		}
	}
	var removed []string
	for _, path := range plan.remove {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			errs = append(errs, fmt.Errorf("remove %s: %w", filepath.Base(path), err))
			continue
		}
		removed = append(removed, path)
	}
	if err := c.systemd.DaemonReload(ctx); err != nil {
		errs = append(errs, fmt.Errorf("daemon-reload: %w", err))
	}
	if err := errors.Join(errs...); err != nil {
		return nil, fmt.Errorf("failed to remove timer: %w", err)
	}

	return &DaemonActionResult{
		Success:     true,
		Packaged:    packaged,
		UnitFiles:   removed,
		KeptFiles:   plan.keep,
		MaskedFiles: plan.masked,
		Message:     "Auto-update daemon disabled" + notes,
	}, nil
}

// keptNote returns the message suffix that names the unit files that
// DisableDaemon kept, or "" when it kept none.
func keptNote(kept []string) string {
	if len(kept) == 0 {
		return ""
	}
	return fmt.Sprintf("; kept %s (not written by updex; remove by hand if unwanted)", strings.Join(kept, " and "))
}

// maskedNote returns the message suffix that names the unit files that are
// masked (symlinks to /dev/null) and how to undo each mask, or "" when none
// is masked.
func maskedNote(masked []string) string {
	if len(masked) == 0 {
		return ""
	}
	names := make([]string, len(masked))
	for i, path := range masked {
		names[i] = filepath.Base(path)
	}
	verb := "is"
	if len(names) > 1 {
		verb = "are"
	}
	// One command for every mask: "and" between two commands would read as
	// unit names to a shell.
	return fmt.Sprintf("; %s %s masked (run 'systemctl unmask %s' to undo)", strings.Join(names, " and "), verb, strings.Join(names, " "))
}

// daemonUnitFileInUse returns the path of the unit file that systemd uses
// for the unit named daemonUnitName+suffix: the file in the /etc unit
// directory when one exists (it overrides), else the packaged file when one
// exists. ok is false when neither exists.
func (c *Client) daemonUnitFileInUse(suffix string) (path, source string, ok bool) {
	return c.unitFileInUse(daemonUnitName + suffix)
}

// unitFileInUse returns the path of the unit file named file (for example
// "updex-suite-switch.service") that systemd uses: the one in the /etc unit
// directory when it exists, else the packaged one. ok is false when neither
// exists.
func (c *Client) unitFileInUse(file string) (path, source string, ok bool) {
	candidates := []struct{ dir, source string }{
		{c.systemd.UnitPath, DaemonSourceEtc},
		{c.systemd.PackagedUnitPath, DaemonSourcePackaged},
	}
	for _, candidate := range candidates {
		if candidate.dir == "" {
			continue
		}
		p := filepath.Join(candidate.dir, file)
		if _, err := os.Lstat(p); err == nil || !os.IsNotExist(err) {
			return p, candidate.source, true
		}
	}
	return "", "", false
}

// DaemonStatus reports whether the automatic update timer is installed,
// enabled, and active, which unit files are in use, its schedule, the next
// run, and the time and result of the last run. It also reads the persistent
// last-update record, even without a timer. This takes no lock and writes
// nothing; an unreadable or invalid record sets LastUpdateError, not an error.
//
// Installed means a timer unit file exists in /etc/systemd/system or in the
// packaged directory. Source is "etc" when the timer file in use is in
// /etc/systemd/system (it overrides the packaged one), else "packaged". The
// next run and the last run come from systemd (`systemctl show`): the
// timer's NextElapseUSecRealtime, and the service's ExecMainExitTimestamp and
// Result. They are returned as systemd prints them. NextRun is empty when no
// run is scheduled (the timer is not active). LastRun and LastResult are empty
// when the service never ran since boot. A runner that cannot read properties
// leaves all three empty.
//
// Schedule is the timer's effective OnCalendar schedule, as a
// comma-separated list: the TimersCalendar property that systemd reports,
// which already includes administrator drop-ins and an empty OnCalendar=
// assignment that resets the list, or, when systemd cannot report it, the
// schedule computed from the unit file in use and its drop-ins by systemd's
// rules. A masked timer (a symlink to /dev/null) reports Masked and no
// schedule: it never fires.
func (c *Client) DaemonStatus(ctx context.Context, _ DaemonStatusOptions) (*DaemonStatusResult, error) {
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("get daemon status: %w", err)
	}

	lastUpdate, err := readLastRunStatus(c.paths.lastRunPath)
	status := &DaemonStatusResult{LastUpdate: lastUpdate}
	if err != nil {
		status.LastUpdateError = err.Error()
	}
	timerPath, source, timerFound := c.daemonUnitFileInUse(".timer")
	if !timerFound {
		return status, nil
	}
	status.Installed = true
	status.Source = source
	for _, suffix := range []string{".timer", ".service"} {
		if path, _, ok := c.daemonUnitFileInUse(suffix); ok {
			status.UnitFiles = append(status.UnitFiles, path)
		}
	}
	timerUnit := daemonUnitName + ".timer"
	status.Masked = isMaskLink(timerPath)
	if !status.Masked {
		status.Schedule = c.daemonSchedule(ctx, timerUnit, timerPath)
	}

	// The boot-time unit (ADR-0021), when a file of it exists.
	suiteUnit := suiteSwitchUnitName + ".service"
	if path, _, ok := c.unitFileInUse(suiteUnit); ok {
		status.UnitFiles = append(status.UnitFiles, path)
		status.SuiteSwitchInstalled = true
		enabled, err := c.systemd.IsEnabled(ctx, suiteUnit)
		if err != nil {
			return nil, fmt.Errorf("get daemon status: query enabled state of %s: %w", suiteUnit, err)
		}
		status.SuiteSwitchEnabled = enabled
	}

	enabled, err := c.systemd.IsEnabled(ctx, timerUnit)
	if err != nil {
		return nil, fmt.Errorf("get daemon status: query enabled state: %w", err)
	}
	active, err := c.systemd.IsActive(ctx, timerUnit)
	if err != nil {
		return nil, fmt.Errorf("get daemon status: query active state: %w", err)
	}
	status.Enabled = enabled
	status.Active = active

	next, err := c.showDaemonProperty(ctx, timerUnit, "NextElapseUSecRealtime")
	if err != nil {
		return nil, fmt.Errorf("get daemon status: query next run: %w", err)
	}
	status.NextRun = next
	serviceUnit := daemonUnitName + ".service"
	last, err := c.showDaemonProperty(ctx, serviceUnit, "ExecMainExitTimestamp")
	if err != nil {
		return nil, fmt.Errorf("get daemon status: query last run: %w", err)
	}
	if last != "" {
		result, err := c.showDaemonProperty(ctx, serviceUnit, "Result")
		if err != nil {
			return nil, fmt.Errorf("get daemon status: query last result: %w", err)
		}
		status.LastRun = last
		status.LastResult = result
	}
	return status, nil
}

// showDaemonProperty reads one systemd property and maps "no value" (an empty
// string, "n/a", or "0") to "". A runner without ShowRunner support yields
// "" and no error, because the state is unknown rather than failed.
func (c *Client) showDaemonProperty(ctx context.Context, unit, property string) (string, error) {
	value, err := c.systemd.Show(ctx, unit, property)
	if err != nil {
		if errors.Is(err, systemd.ErrShowUnsupported) {
			return "", nil
		}
		return "", err
	}
	switch value {
	case "n/a", "0":
		return "", nil
	}
	return value, nil
}

// daemonSchedule returns the effective OnCalendar schedule of the timer unit,
// as a comma-separated list, or "" when it is unknown.
//
// It prefers what systemd reports: the timer's TimersCalendar property
// already accounts for administrator drop-ins and for the reset meaning of an
// empty OnCalendar= assignment. When systemd cannot answer (a runner without
// Show support, a systemctl failure, or output with no calendar trigger), it
// computes the schedule from the unit file at timerPath and its drop-ins by
// systemd's rules. Reading the schedule is best-effort: it never fails the
// status.
func (c *Client) daemonSchedule(ctx context.Context, timerUnit, timerPath string) string {
	if value, err := c.systemd.Show(ctx, timerUnit, "TimersCalendar"); err == nil {
		if values := parseTimersCalendar(value); len(values) > 0 {
			return strings.Join(values, ", ")
		}
	}
	return c.scheduleFromUnitFiles(timerUnit, timerPath)
}

// parseTimersCalendar extracts the OnCalendar= values from the value of
// systemd's TimersCalendar property, in order.
//
// `systemctl show -p TimersCalendar --value` prints one entry per calendar
// trigger, in the shape src/systemctl/systemctl-show.c prints it:
//
//	{ OnCalendar=*-*-* 00/6:00:00 ; next_elapse=Fri 2026-10-23 18:00:00 EDT }
//
// with several entries following each other on separate lines. The parser
// depends only on that shape: it takes each OnCalendar= value up to the " ;"
// separator before next_elapse (or up to the closing brace), so entries
// separated by spaces parse the same, and odd input yields no values, which
// makes the caller fall back to the files. It never panics.
func parseTimersCalendar(value string) []string {
	var values []string
	rest := value
	for {
		_, after, ok := strings.Cut(rest, "OnCalendar=")
		if !ok {
			return values
		}
		rest = after
		end := len(rest)
		for _, terminator := range [...]string{" ;", "}", "\n"} {
			if i := strings.Index(rest, terminator); i >= 0 && i < end {
				end = i
			}
		}
		if spec := strings.TrimSpace(rest[:end]); spec != "" {
			values = append(values, spec)
		}
		// Each iteration drops at least the OnCalendar= prefix, so the loop
		// always ends.
		rest = rest[end:]
	}
}

// scheduleFromUnitFiles computes the OnCalendar schedule that systemd would
// apply to the timer from its unit files: the file in use first, then the
// drop-ins (<unit>.d/*.conf, see systemd.Manager.UnitDropIns) sorted by name,
// each applied after the file it overrides.
//
// Only [Timer] sections count. Inside one, OnCalendar=value adds a trigger
// and an empty OnCalendar= clears the list so far, which is systemd's reset
// rule (systemd.timer(5)). A file that cannot be read or is not a regular
// file is skipped; the values are joined with ", ".
func (c *Client) scheduleFromUnitFiles(timerUnit, timerPath string) string {
	content, ok := readScheduleFile(timerPath)
	if !ok {
		return ""
	}
	values := parseOnCalendar(content, nil)
	for _, path := range c.systemd.UnitDropIns(timerUnit) {
		content, ok := readScheduleFile(path)
		if !ok {
			continue
		}
		values = parseOnCalendar(content, values)
	}
	return strings.Join(values, ", ")
}

// readScheduleFile reads a unit or drop-in file for its schedule. It uses
// os.Lstat and refuses anything that is not a regular file, so it never reads
// through a symlink or a directory (ADR-0005), and it bounds the read with
// maxUnitRead. ok is false when the file cannot be read or is not regular.
func readScheduleFile(path string) (content string, ok bool) {
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() {
		return "", false
	}
	content, err = readUnitFile(path)
	if err != nil {
		return "", false
	}
	return content, true
}

// parseOnCalendar returns values with the OnCalendar= assignments of the
// [Timer] sections of a unit or drop-in file applied: a value appends, and an
// empty value clears the list so far (systemd's reset rule). Blank lines,
// comments, and lines outside a [Timer] section are ignored.
func parseOnCalendar(content string, values []string) []string {
	inTimer := false
	for line := range strings.SplitSeq(content, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, ";") {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			inTimer = line == "[Timer]"
			continue
		}
		if !inTimer {
			continue
		}
		value, ok := strings.CutPrefix(line, "OnCalendar=")
		if !ok {
			continue
		}
		if value = strings.TrimSpace(value); value == "" {
			values = nil
			continue
		}
		values = append(values, value)
	}
	return values
}
