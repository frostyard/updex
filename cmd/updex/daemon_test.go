// daemonPackagedEnv is daemonTestEnv plus a packaged unit directory that
// stands in for /usr/lib/systemd/system, seeded with the generated units when
// seed is set.
func daemonPackagedEnv(t *testing.T, mock *systemd.MockSystemctlRunner, seed bool) (etcDir, packagedDir string) {
	t.Helper()
	etcDir = daemonTestEnv(t, mock)
	packagedDir = t.TempDir()
	systemdManager.PackagedUnitPath = packagedDir
	if seed {
		timer, service := sdk.DaemonUnits()
		for name, content := range map[string]string{
			daemonTestUnitName + ".timer":   systemd.GenerateTimer(timer),
			daemonTestUnitName + ".service": systemd.GenerateService(service),
		} {
			if err := os.WriteFile(filepath.Join(packagedDir, name), []byte(content), 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	return etcDir, packagedDir
}

func TestRunDaemonEnable_PackagedUnitsWriteNothing(t *testing.T) {
	for _, jsonOut := range []bool{true, false} {
		t.Run(map[bool]string{true: "json", false: "text"}[jsonOut], func(t *testing.T) {
			mock := &systemd.MockSystemctlRunner{}
			etcDir, packagedDir := daemonPackagedEnv(t, mock, true)
			clix.JSONOutput = jsonOut

			out, err := captureStdout(t, func() error { return runDaemonEnable(daemonTestCommand(t), nil) })
			if err != nil {
				t.Fatalf("enable failed: %v", err)
			}
			entries, readErr := os.ReadDir(etcDir)
			if readErr != nil || len(entries) != 0 {
				t.Errorf("enable wrote to the /etc unit directory: %v %v", entries, readErr)
			}
			if !mock.EnableCalled || !mock.StartCalled || mock.EnableUnit != daemonTestUnitName+".timer" {
				t.Errorf("enable/start = %v/%v on %q, want the packaged timer enabled and started", mock.EnableCalled, mock.StartCalled, mock.EnableUnit)
			}
			if mock.DaemonReloadCalled {
				t.Error("enable reloaded systemd although it wrote nothing")
			}
			if jsonOut {
				var result sdk.DaemonActionResult
				if err := json.Unmarshal([]byte(out), &result); err != nil {
					t.Fatalf("enable JSON invalid: %v\n%s", err, out)
				}
				want := []string{filepath.Join(packagedDir, daemonTestUnitName+".timer"), filepath.Join(packagedDir, daemonTestUnitName+".service")}
				if !result.Success || !result.Packaged || strings.Join(result.UnitFiles, ",") != strings.Join(want, ",") {
					t.Errorf("enable result = %+v, want packaged units %v", result, want)
				}
				return
			}
			for _, want := range []string{"Auto-update daemon enabled.", "no unit file was written", "every 6 hours"} {
				if !strings.Contains(out, want) {
					t.Errorf("enable output missing %q:\n%s", want, out)
				}
			}
		})
	}
}

