func TestRunDaemonDisable_KeepsUnmarkedUnit(t *testing.T) {
	mock := &systemd.MockSystemctlRunner{}
	etcDir, _ := daemonPackagedEnv(t, mock, false)
	seedUnits(t, etcDir)
	// An OS image can ship a unit of this name in /etc; it has no marker.
	foreign := filepath.Join(etcDir, daemonTestUnitName+".service")
	if err := os.WriteFile(foreign, []byte("[Service]\nExecStart=/bin/true\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	clix.JSONOutput = true

	out, err := captureStdout(t, func() error { return runDaemonDisable(daemonTestCommand(t), nil) })
	if err != nil {
		t.Fatalf("disable failed: %v", err)
	}
	if _, statErr := os.Stat(foreign); statErr != nil {
		t.Errorf("disable removed the unmarked unit: %v", statErr)
	}
	if _, statErr := os.Stat(filepath.Join(etcDir, daemonTestUnitName+".timer")); !os.IsNotExist(statErr) {
		t.Errorf("disable kept the marked timer: %v", statErr)
	}
	var result sdk.DaemonActionResult
	if err := json.Unmarshal([]byte(out), &result); err != nil {
		t.Fatalf("disable JSON invalid: %v\n%s", err, out)
	}
	if len(result.KeptFiles) != 1 || result.KeptFiles[0] != foreign || !strings.Contains(result.Message, "kept") {
		t.Errorf("disable result = %+v, want the unmarked unit reported as kept", result)
	}
}

